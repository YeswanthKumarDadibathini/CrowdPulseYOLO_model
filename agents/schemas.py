"""
CrowdPulse - Multi-Agent Data Schemas (Phase 4)
Project: CrowdPulse - Crowd Density Management System (SIH25165)
Phase: Phase 4 Multi-Agent Coordination

Beginner-Friendly Explanation:
In a multi-agent system, agents communicate by sending structured messages to each other.
Dataclasses define the exact format of these messages (like forms or envelopes)
so each agent knows what data to expect.

We define:
1. ZoneTelemetry: Current state reported by the Monitor Agent
2. AnomalyReport: Danger or surge detected by the Anomaly Agent
3. DispatchAction: Emergency action or order generated by the Dispatch Agent
4. AgentMessage: Envelope containing communications between agents
"""

from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional


def utc_now():
    return datetime.now(timezone.utc).replace(tzinfo=None)


@dataclass
class ZoneTelemetry:
    """Telemetry data measured by the Monitor Agent for a single zone."""

    zone_id: str
    zone_name: str
    timestamp: datetime
    current_count: int
    capacity_limit: int
    occupancy_pct: float
    surge_rate_per_min: float = 0.0  # Rate of change: (count_now - count_prev) / time
    bottleneck_detected: bool = False
    hotspot_count: int = 0
    inference_latency_ms: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["timestamp"] = self.timestamp.isoformat()
        return d


@dataclass
class AnomalyReport:
    """Report generated by the Anomaly Agent when dangerous patterns are discovered."""

    anomaly_id: str
    zone_id: str
    zone_name: str
    timestamp: datetime
    anomaly_type: str  # "SUDDEN_SURGE", "STATIC_BOTTLENECK", "CRITICAL_OVERCROWDING", "RAPID_INFLOW"
    severity: str      # "LOW", "MEDIUM", "HIGH", "CRITICAL"
    confidence: float  # 0.0 to 1.0 (e.g. 0.92 = 92% confidence)
    description: str
    metrics: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["timestamp"] = self.timestamp.isoformat()
        return d


@dataclass
class DispatchAction:
    """Action plan formulated by the Dispatch Agent to alleviate dangerous conditions."""

    action_id: str
    anomaly_id: str
    zone_id: str
    timestamp: datetime
    action_type: str  # "DISPATCH_SECURITY", "RESTRICT_TURNSTILES", "OPEN_EVACUATION_GATE", "BROADCAST_AUDIO"
    target_team: str  # e.g., "Rapid Response Squad Alpha", "Digital PA System", "Gate Control"
    priority: str     # "NORMAL", "HIGH", "URGENT"
    instructions: str
    status: str = "PENDING"  # "PENDING", "EXECUTED", "RESOLVED"

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["timestamp"] = self.timestamp.isoformat()
        return d


@dataclass
class AgentMessage:
    """Standard message passed between agents in the coordination bus."""

    sender: str        # "MonitorAgent", "AnomalyAgent", "DispatchAgent", "Coordinator"
    recipient: str     # Target agent or "BROADCAST"
    message_type: str  # "TELEMETRY", "ANOMALY_ALERT", "ACTION_ORDER", "STATUS_UPDATE"
    content: Dict[str, Any]
    timestamp: datetime = field(default_factory=utc_now)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "sender": self.sender,
            "recipient": self.recipient,
            "message_type": self.message_type,
            "content": self.content,
            "timestamp": self.timestamp.strftime("%H:%M:%S"),
        }
